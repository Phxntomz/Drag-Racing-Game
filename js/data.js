export function classForBuild(build) {
  for (const id of ["street", "sport", "pro", "outlaw"]) {
    const caps = CLASS_CAPS[id];
    const fits = Object.keys(caps).every((slot) => (build[slot] || 0) <= caps[slot]);
    if (fits) return id;
  }
  return "outlaw";
}

export function canEnter(build, classId) {
  return CLASS_RANK[classForBuild(build)] <= CLASS_RANK[classId];
}

export function unmetRequires(car, build, slot, level) {
  const group = partGroups(car).find((item) => item.id === slot);
  const option = group.options.find((item) => item.level === level);
  if (!option?.requires) return [];
  return option.requires.filter((req) => req.reason && (build[req.slot] || 0) < req.min);
}

export function optionCost(car, slot, level) {
  const group = partGroups(car).find((item) => item.id === slot);
  const option = group.options.find((item) => item.level === level);
  const factor = 0.78 + car.price / 120000;
  return Math.round((option?.cost || 0) * factor);
}

